/* ── i18n Engine ── */
const i18n = {
  currentLang: 'es',

  init() {
    const saved = localStorage.getItem('cl-lang');
    if (saved && translations[saved]) {
      this.currentLang = saved;
    }
    this.apply();
    this.updateSwitcher();
    document.documentElement.lang = this.currentLang;
    document.documentElement.setAttribute('data-lang', this.currentLang);
  },

  setLang(lang) {
    if (!translations[lang] || lang === this.currentLang) return;
    this.currentLang = lang;
    localStorage.setItem('cl-lang', lang);
    this.apply();
    this.updateSwitcher();
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-lang', lang);
  },

  t(key) {
    return translations[this.currentLang]?.[key] || translations.es[key] || key;
  },

  apply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = val;
      } else {
        el.textContent = val;
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const val = this.t(key);
      el.innerHTML = val;
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      el.setAttribute('aria-label', this.t(key));
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      const key = el.getAttribute('data-i18n-alt');
      el.setAttribute('alt', this.t(key));
    });
  },

  updateSwitcher() {
    document.querySelectorAll('.lang-switcher__btn').forEach(btn => {
      btn.classList.toggle('is-active', btn.dataset.lang === this.currentLang);
    });
  }
};
